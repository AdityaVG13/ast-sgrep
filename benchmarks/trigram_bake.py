#!/usr/bin/env python3
"""Bake the static trigram rarity table for one-shot Match (no df preload).

Counts trigram occurrences over lowercased lines of a large code corpus,
emitting a Rust `[(u32, u32)]` (packed trigram key, occurrence count) sorted
by key for binary search. Unknown trigrams (absent here) are treated as
rarest at lookup.

Regenerate with:
    python3 benchmarks/trigram_bake.py <corpus-root>... > crates/ast-sgrep-core/src/store/trigram_static_data.rs

Deterministic given the corpus (sorted output). Binary-search lookup is
zero-init: no per-process build cost. Entries below --min-count (default
100) are dropped: absent reads as 0=rarest at lookup, and the scan-budget
fallback in passes::literal bounds any locally-flooding pick, so the tail
costs size without buying picks.
"""
import os
import sys
from collections import Counter

BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".webp", ".bmp", ".tiff",
    ".woff", ".woff2", ".ttf", ".otf", ".eot",
    ".exe", ".dll", ".so", ".dylib", ".a", ".o", ".rlib", ".rmeta",
    ".zip", ".tar", ".gz", ".bz2", ".xz", ".7z", ".rar",
    ".pdf", ".mp3", ".mp4", ".mov", ".wav", ".ogg",
    ".sqlite", ".db", ".bin", ".dat", ".onnx", ".pt", ".pth", ".safetensors",
}
SKIP_DIRS = {"target", ".git", "node_modules", "__pycache__", ".hg", ".svn"}


def iter_files(roots):
    for root in roots:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
            for fn in filenames:
                if os.path.splitext(fn)[1].lower() in BINARY_EXTS:
                    continue
                yield os.path.join(dirpath, fn)


def main(roots, min_count):
    counts: Counter = Counter()
    nfiles, nlines = 0, 0
    for path in iter_files(roots):
        try:
            with open(path, "rb") as f:
                data = f.read()
        except OSError:
            continue
        nfiles += 1
        for line in data.split(b"\n"):
            # bytes.lower folds ASCII only — exactly the query domain
            # (non-ASCII needles take Full; ASCII needles fold identically).
            b = line.lower()
            nlines += 1
            for i in range(len(b) - 2):
                a, c0, c1 = b[i], b[i + 1], b[i + 2]
                if a < 128 and c0 < 128 and c1 < 128:
                    counts[(a << 16) | (c0 << 8) | c1] += 1
    kept = sorted(k for k, v in counts.items() if v >= min_count)
    print(
        f"// @generated by benchmarks/trigram_bake.py --min-count {min_count} from {roots}",
        file=sys.stderr,
    )
    print(
        f"// {len(kept)}/{len(counts)} trigrams over {nfiles} files / {nlines} lines",
        file=sys.stderr,
    )
    print("// Static trigram occurrence counts, sorted by packed key (binary search).")
    print("// Rank semantics: HIGHER count = more common. Absent = rarest.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) const TRIGRAM_BAKE: [(u32, u32); {len(kept)}] = [")
    for key in kept:
        print(f"    (0x{key:06x}, {counts[key]}),")
    print("];")


if __name__ == "__main__":
    args = sys.argv[1:]
    min_count = 100
    if args[:1] == ["--min-count"]:
        min_count = int(args[1])
        args = args[2:]
    main(args or ["crates"], min_count)
